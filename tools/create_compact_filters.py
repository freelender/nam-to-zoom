"""Maintainer: reproducible FIR tables for Compact effect runtime only."""
from pathlib import Path
import numpy as np
from scipy.signal import firwin

ROOT = Path(__file__).resolve().parents[1]

def coefficients():
    # 132.3 kHz is both 44.1k*3 and 33.075k*4. The 14.5 kHz cutoff
    # balances guitar bandwidth with rejection above the internal Nyquist.
    prototype = firwin(193, 14500, fs=132300, window=("kaiser", 5.65))
    tables = []
    for factor in (3, 4):
        table = prototype.copy()
        for phase in range(factor):
            table[phase::factor] /= np.sum(table[phase::factor])
        tables.append(table.astype(np.float32))
    return tables

if __name__ == "__main__":
    lines = ["/* Generated by tools/create_compact_filters.py. Float32, per-phase unity DC. */",
             "#ifndef N2Z_COMPACT_FILTERS_H", "#define N2Z_COMPACT_FILTERS_H"]
    for name, table, factor, stride in zip(("Down", "Up"), coefficients(), (3,4), (66,50)):
        lines.append(f"static const float N2Z_{name}PhaseCoefficients[{factor}][{stride}] = {{")
        for phase in range(factor):
            row = np.zeros(stride, dtype=np.float32)
            row[:len(table[phase::factor])] = table[phase::factor]
            lines.append("  {")
            for start in range(0, stride, 4):
                lines.append("    " + ", ".join(f"{float(x):.9e}f" for x in row[start:start+4]) + ",")
            lines.append("  },")
        lines.append("};")
    lines += ["#endif", ""]
    (ROOT / "dsp/nam_a2_own_host/compact_filters.h").write_bytes("\n".join(lines).encode("ascii"))
